/**
 * ゲームジャンルとゲーム名からペルソナを取得する
 * @param genre ゲームジャンル (fps, rpg, moba, survival, action, other)
 * @param gameName ゲーム名（ペルソナのカスタマイズに使用）
 */
export function getPersona(genre: string, gameName: string): Persona {
  const normalizedGenre = genre.toLowerCase();
  const base = personas[normalizedGenre] ?? personas['other'];

  // ゲーム名が指定されている場合はシステムプロンプトにゲーム名を追加
  if (gameName && gameName.trim() !== '') {
    return {
      ...base,
      systemPrompt: `${base.systemPrompt}\n\n現在のゲーム: ${gameName}\nこのゲームの文脈を踏まえてアドバイスしてください。`,
    };
  }

  return base;
}
