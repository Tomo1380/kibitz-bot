/**
 * ゲーム名から追加コンテキスト文字列を取得する
 * @param gameName ゲーム名（部分一致で検索）
 * @returns ヒントとよくあるミスを結合した文字列、見つからなければ null
 */
export function getGameContext(gameName: string | undefined | null): string | null {
  if (!gameName || gameName.trim() === '') {
    return null;
  }

  const normalized = gameName.toLowerCase().trim();

  const entry = gameKnowledgeBase.find((e) =>
    e.gameName.includes(normalized) || normalized.includes(e.gameName)
  );

  if (!entry) {
    return null;
  }

  const tipsText = entry.tips
    .slice(0, 5)
    .map((tip, i) => `${i + 1}. ${tip}`)
    .join('\n');

  const mistakesText = entry.commonMistakes
    .slice(0, 3)
    .map((m, i) => `${i + 1}. ${m}`)
    .join('\n');

  return `【${entry.gameName} の攻略知識】\n\n汎用ヒント:\n${tipsText}\n\nよくあるミス:\n${mistakesText}`;
}
